"""``cornea open``: show the web UI in a native window."""

import typer

from cornea import preload
from cornea.cli import options, output
from cornea.cli.commands import (
    AllowedHost,
    ApiPrefix,
    AppDir,
    AppIdFlag,
    AsgiFlag,
    ContextMenu,
    CookieSameSite,
    Csp,
    CspProfileFlag,
    Debug,
    DevTools,
    DisableAction,
    Downloads,
    DropFiles,
    Frameless,
    HashedPrefix,
    Host,
    IconFlag,
    JsApi,
    JsonFileFlag,
    JsonFriendlyFlag,
    LoadingBackground,
    LoadingFlag,
    LoadingForeground,
    LoadingHtml,
    LoadingIcon,
    LoadingMinDisplay,
    LoadingSubtitle,
    LoadingTheme,
    LoadingTitle,
    LogFileFlag,
    LogLevelFlag,
    MeasureFlag,
    MinSize,
    ModeFlag,
    Notifications,
    OnTop,
    OpenFiles,
    PackageFlag,
    PackagePath,
    Port,
    Position,
    PublicPath,
    RememberWindowFlag,
    RequireOrigin,
    Resizable,
    RunCwd,
    RunFlag,
    RunTimeout,
    SingleInstanceFlag,
    Size,
    SourceArgument,
    SpaFlag,
    Title,
    TokenTtl,
    UrlFlag,
    WebDist,
    WsgiFlag,
    app,
    epilog,
    launch,
    logging_options,
    measure_option,
    source_arguments,
)


@app.command("open", epilog=epilog("open"))
def open_window(
    ctx: typer.Context,
    source: SourceArgument = None,
    web_dist: WebDist = None,
    url: UrlFlag = None,
    mode: ModeFlag = None,
    run: RunFlag = None,
    run_cwd: RunCwd = None,
    run_timeout: RunTimeout = None,
    asgi: AsgiFlag = None,
    wsgi: WsgiFlag = None,
    app_dir: AppDir = None,
    package: PackageFlag = None,
    package_path: PackagePath = None,
    spa: SpaFlag = None,
    hashed_prefix: HashedPrefix = None,
    host: Host = None,
    port: Port = None,
    allowed_host: AllowedHost = None,
    csp: Csp = None,
    csp_profile: CspProfileFlag = None,
    api_prefix: ApiPrefix = None,
    token_ttl: TokenTtl = None,
    cookie_samesite: CookieSameSite = None,
    public_path: PublicPath = None,
    require_origin: RequireOrigin = None,
    disable_action: DisableAction = None,
    open_files: OpenFiles = None,
    notifications: Notifications = None,
    title: Title = None,
    size: Size = None,
    min_size: MinSize = None,
    position: Position = None,
    frameless: Frameless = None,
    resizable: Resizable = None,
    on_top: OnTop = None,
    context_menu: ContextMenu = None,
    devtools: DevTools = None,
    debug: Debug = None,
    js_api: JsApi = None,
    drop_files: DropFiles = None,
    downloads: Downloads = None,
    icon: IconFlag = None,
    loading: LoadingFlag = None,
    loading_subtitle: LoadingSubtitle = None,
    loading_title: LoadingTitle = None,
    loading_icon: LoadingIcon = None,
    loading_theme: LoadingTheme = None,
    loading_background: LoadingBackground = None,
    loading_foreground: LoadingForeground = None,
    loading_html: LoadingHtml = None,
    loading_min_display: LoadingMinDisplay = None,
    app_id: AppIdFlag = None,
    single_instance: SingleInstanceFlag = None,
    remember_window: RememberWindowFlag = None,
    log_level: LogLevelFlag = None,
    log_file: LogFileFlag = None,
    measure: MeasureFlag = None,
    json_friendly: JsonFriendlyFlag = None,
    json_file: JsonFileFlag = None,
) -> None:
    """Show the web UI in a native window (Windows)."""
    preload()  # load the server while the options below are read
    try:
        web_source = options.build_source(
            argument=source,
            **source_arguments(
                ctx,
                source,
                web_dist=web_dist,
                url=url,
                asgi=asgi,
                wsgi=wsgi,
                app_dir=app_dir,
                package=package,
                package_path=package_path,
                spa=spa,
                hashed_prefix=hashed_prefix,
                mode=mode,
                run=run,
                run_cwd=run_cwd,
                run_timeout=run_timeout,
            ),
        )
        window = options.build_window(
            title=title,
            size=size,
            min_size=min_size,
            position=position,
            frameless=frameless,
            resizable=resizable,
            on_top=on_top,
            context_menu=context_menu,
            devtools=devtools,
            debug=debug,
            js_api=js_api,
            drop_files=drop_files,
            downloads=downloads,
            icon=icon,
        )
        loading_screen = options.build_loading(
            enabled=loading,
            subtitle=loading_subtitle,
            title=loading_title,
            icon=loading_icon,
            theme=loading_theme,
            background=loading_background,
            foreground=loading_foreground,
            html=loading_html,
            min_display=loading_min_display,
        )
        server = options.build_server(host=host, port=port)
        security = options.build_security(
            allowed_host=allowed_host,
            csp=csp,
            api_prefix=api_prefix,
            token_ttl=token_ttl,
            cookie_samesite=cookie_samesite,
            public_path=public_path,
            require_origin=require_origin,
            csp_profile=csp_profile,
        )
        bridge = options.build_bridge(
            disable_action=disable_action, open_files=open_files, notifications=notifications
        )
        identity = options.build_app(
            app_id=app_id, single_instance=single_instance, remember_window=remember_window
        )
    except ValueError as exc:
        output.error(str(exc))
        raise typer.Exit(code=1) from exc
    launch(
        ctx,
        web_source,
        window,
        loading=loading_screen,
        server=server,
        security=security,
        bridge=bridge,
        identity=identity,
        logging_options=logging_options(log_level, log_file, debug),
        measure=measure_option(measure, json_friendly, json_file),
    )
